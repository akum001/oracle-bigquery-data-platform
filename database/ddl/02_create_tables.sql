ALTER SESSION SET CURRENT_SCHEMA = src_erp;

CREATE TABLE customers (
    customer_id     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_code   VARCHAR2(20) NOT NULL UNIQUE,
    full_name       VARCHAR2(120) NOT NULL,
    email           VARCHAR2(150) NOT NULL UNIQUE,
    segment         VARCHAR2(30) DEFAULT 'RETAIL' CHECK (segment IN ('RETAIL', 'SMB', 'ENTERPRISE')),
    country_code    CHAR(2) NOT NULL,
    city            VARCHAR2(80),
    is_active       NUMBER(1) DEFAULT 1 CHECK (is_active IN (0, 1)),
    created_at      TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at      TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE TABLE products (
    product_id      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku             VARCHAR2(30) NOT NULL UNIQUE,
    product_name    VARCHAR2(150) NOT NULL,
    category        VARCHAR2(60) NOT NULL,
    unit_price      NUMBER(10, 2) NOT NULL CHECK (unit_price >= 0),
    unit_cost       NUMBER(10, 2) NOT NULL CHECK (unit_cost >= 0),
    is_active       NUMBER(1) DEFAULT 1 CHECK (is_active IN (0, 1)),
    created_at      TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at      TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE TABLE orders (
    order_id        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_number    VARCHAR2(30) NOT NULL UNIQUE,
    customer_id     NUMBER NOT NULL REFERENCES customers(customer_id),
    order_status    VARCHAR2(20) NOT NULL CHECK (order_status IN ('PENDING', 'CONFIRMED', 'SHIPPED', 'DELIVERED', 'CANCELLED')),
    currency_code   CHAR(3) DEFAULT 'USD' NOT NULL,
    order_date      TIMESTAMP NOT NULL,
    updated_at      TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE TABLE order_items (
    order_item_id   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id        NUMBER NOT NULL REFERENCES orders(order_id),
    product_id      NUMBER NOT NULL REFERENCES products(product_id),
    quantity        NUMBER(10) NOT NULL CHECK (quantity > 0),
    unit_price      NUMBER(10, 2) NOT NULL CHECK (unit_price >= 0),
    discount_pct    NUMBER(5, 2) DEFAULT 0 CHECK (discount_pct BETWEEN 0 AND 100),
    updated_at      TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE INDEX idx_customers_updated ON customers(updated_at);
CREATE INDEX idx_products_updated ON products(updated_at);
CREATE INDEX idx_orders_updated ON orders(updated_at);
CREATE INDEX idx_order_items_updated ON order_items(updated_at);

CREATE OR REPLACE TRIGGER trg_customers_upd BEFORE UPDATE ON customers
FOR EACH ROW BEGIN :NEW.updated_at := CURRENT_TIMESTAMP; END;
/

CREATE OR REPLACE TRIGGER trg_products_upd BEFORE UPDATE ON products
FOR EACH ROW BEGIN :NEW.updated_at := CURRENT_TIMESTAMP; END;
/

CREATE OR REPLACE TRIGGER trg_orders_upd BEFORE UPDATE ON orders
FOR EACH ROW BEGIN :NEW.updated_at := CURRENT_TIMESTAMP; END;
/

CREATE OR REPLACE TRIGGER trg_order_items_upd BEFORE UPDATE ON order_items
FOR EACH ROW BEGIN :NEW.updated_at := CURRENT_TIMESTAMP; END;
/
